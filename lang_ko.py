def normalize_text(s):
    """파일시스템에서 읽은 이름을 프로그램 안에서 쓸 형태로 통일합니다.

    ⚠ macOS 는 한글을 자모로 쪼개서(NFD) 저장합니다.
      '스크린샷' 이 ㅅ+ㅡ+ㅋ+ㅡ+ㄹ+ㅣ+ㄴ+ㅅ+ㅑ+ㅅ 으로 들어옵니다.
      아래 정규식들은 합쳐진 형태(NFC)로 쓰여 있으므로 반드시 통일해야 합니다.
    """
    return unicodedata.normalize("NFC", s)


# 이 언어의 글자가 들어 있는가
#   가-힣         합쳐진 글자 (NFC)
#   ㄱ-ㅎㅏ-ㅣ      호환용 자모 (ㅁㄴㅇㄹ 같이 직접 친 것)
#   \u1100-\u11FF 조합용 자모 (macOS 가 쓰는 NFD 형태)
#
#   ⚠ 마지막 대역이 빠져 있어서 한글 파일명이 전부 '한글 아님' 으로
#     세어진 적이 있습니다. NFC 변환이 근본 해결이지만 여기서도 방어합니다.
SCRIPT_RE = re.compile(r"[가-힣ㄱ-ㅎㅏ-ㅣ\u1100-\u11FF]")

# 낱말을 가르는 문자
